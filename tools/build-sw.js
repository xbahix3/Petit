// Writes sw.js with the list of every file the game needs, so it works offline.
// Run after changing any asset: node tools/build-sw.js
const fs = require('fs'), path = require('path'), crypto = require('crypto');
const root = path.resolve(__dirname, '..');
const include = ['index.html', 'manifest.webmanifest', 'css', 'js', 'fonts', 'audio', 'icons', 'img'];
const files = [];
(function walk(rel) {
  const abs = path.join(root, rel);
  if (fs.statSync(abs).isDirectory()) fs.readdirSync(abs).sort().forEach((f) => walk(path.join(rel, f)));
  else files.push(rel.split(path.sep).join('/'));
})('');
const list = files.filter((f) => include.some((p) => f === p || f.startsWith(p + '/')));
const hash = crypto.createHash('sha1');
list.forEach((f) => hash.update(f).update(fs.readFileSync(path.join(root, f))));
const version = hash.digest('hex').slice(0, 10);
const sw = `/* Le Petit Ranger — offline cache. Generated by tools/build-sw.js, do not edit by hand. */
'use strict';
var CACHE = 'petit-ranger-${version}';
var ASSETS = ${JSON.stringify(['./'].concat(list), null, 1)};

self.addEventListener('install', function (e) {
  e.waitUntil(caches.open(CACHE).then(function (c) { return c.addAll(ASSETS); }).then(function () { return self.skipWaiting(); }));
});
self.addEventListener('activate', function (e) {
  e.waitUntil(caches.keys().then(function (keys) {
    return Promise.all(keys.filter(function (k) { return k !== CACHE; }).map(function (k) { return caches.delete(k); }));
  }).then(function () { return self.clients.claim(); }));
});
self.addEventListener('fetch', function (e) {
  if (e.request.method !== 'GET') return;
  e.respondWith(caches.match(e.request, { ignoreSearch: true }).then(function (hit) {
    return hit || fetch(e.request).then(function (res) {
      if (res && res.ok && new URL(e.request.url).origin === location.origin) {
        var copy = res.clone();
        caches.open(CACHE).then(function (c) { c.put(e.request, copy); });
      }
      return res;
    }).catch(function () { return caches.match('./index.html'); });
  }));
});
`;
fs.writeFileSync(path.join(root, 'sw.js'), sw);
const bytes = list.reduce((n, f) => n + fs.statSync(path.join(root, f)).size, 0);
console.log(`sw.js: ${list.length} files, ${(bytes / 1024).toFixed(0)} KB, cache ${version}`);
